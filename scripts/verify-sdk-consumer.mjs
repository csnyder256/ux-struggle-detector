import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync, readdirSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = mkdtempSync(path.join(tmpdir(), 'ux-sdk-consumer-'));
const version = readFileSync(path.join(root, 'VERSION'), 'utf8').trim();
const filename = `csnyder256-ux-struggle-sdk-${version}.tgz`;
const archive = process.env.SDK_PACKAGE_FILE || path.join(root, 'dist-sdk', filename);
const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm';
try {
  writeFileSync(path.join(dir, 'package.json'), '{"private":true}');
  execFileSync(npm, ['install', '--offline', '--ignore-scripts', '--no-audit', '--no-fund', archive], { cwd: dir, stdio: 'inherit' });
  const installed = path.join(dir, 'node_modules/@csnyder256/ux-struggle-sdk');
  const pkg = JSON.parse(readFileSync(path.join(installed, 'package.json')));
  assert.equal(pkg.version, version);
  assert.deepEqual(pkg.dependencies || {}, {});
  assert.ok(readdirSync(installed).includes('LICENSE'));
  const names = ['destroySelfHealing','flush','identify','initSelfHealing','renderIntervention','startTour','track'];
  const checks = `if(JSON.stringify(Object.keys(sdk).sort())!==${JSON.stringify(JSON.stringify(names))})throw new Error('Unexpected public exports');
if(typeof window!=='undefined'||typeof document!=='undefined')throw new Error('SSR globals appeared');
sdk.initSelfHealing({orgId:'consumer_test'});sdk.destroySelfHealing();
if(sdk.startTour({steps:[{title:'SSR',copy:'No browser'}]})!==null)throw new Error('Tour not inert in SSR');
`;
  writeFileSync(path.join(dir, 'esm.mjs'), `import * as sdk from '@csnyder256/ux-struggle-sdk';\n${checks}\nconst r=await sdk.flush();if(r.sent!==0)throw new Error('SSR transport started');`);
  writeFileSync(path.join(dir, 'common.cjs'), `const sdk=require('@csnyder256/ux-struggle-sdk');\n${checks}\nsdk.flush().then(r=>{if(r.sent!==0)throw new Error('SSR transport started')});`);
  for (const f of ['esm.mjs', 'common.cjs']) execFileSync(process.execPath, [f], { cwd: dir, stdio: 'inherit' });
  const fixture = `import {initSelfHealing, destroySelfHealing, flush, startTour, track, type InitOptions, type TourStep, type RuntimeEvent} from '@csnyder256/ux-struggle-sdk';
const opts:InitOptions={orgId:'example',onEvent:(e:RuntimeEvent)=>{const kind:string=e.eventType;void kind}};
initSelfHealing(opts);track('example',{count:1});
const steps:TourStep[]=[{title:'Start',copy:'Follow the evidence',selector:'#start'}];
const tour=startTour({steps});tour?.next();tour?.close();
flush().then(r=>{const sent:number=r.sent;void sent});destroySelfHealing();
`;
  for(const f of ['consumer.mts','consumer.cts']) writeFileSync(path.join(dir,f),fixture);
  writeFileSync(path.join(dir,'tsconfig.json'),JSON.stringify({compilerOptions:{strict:true,module:'NodeNext',moduleResolution:'NodeNext',target:'ES2022',lib:['ES2022','DOM'],types:[],noEmit:true},files:['consumer.mts','consumer.cts']}));
  execFileSync(process.execPath,[path.join(root,'node_modules/typescript/bin/tsc'),'-p','tsconfig.json'],{cwd:dir,stdio:'inherit'});
  console.log('SDK packed consumer verified: ESM/CJS runtime, inert SSR, both strict NodeNext typings, license, no runtime dependencies');
} finally { rmSync(dir,{recursive:true,force:true}); }
